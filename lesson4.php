<?php
for ($i = 1; $i <= 100; $i++) {
    // 数値が10の倍数であれば出力
    if ($i % 10 == 0) {
        echo $i . "<br>";
    }
    $sum = 0;

    // 1から100までの数値をループ処理
for ($i = 1; $i <= 100; $i++) {
        // 偶数かどうかチェック（2で割った余りが0なら偶数）
    if ($i % 2 == 0) {
        $sum += $i;  // 偶数の場合は合計に加算
    }
}
for ($i = 1; $i <= 100; $i++) {
    // 15の倍数の場合（3と5の両方の倍数）
    if ($i % 15 == 0) {
        echo "FizzBuzz";
    }
    // 3の倍数の場合
    elseif ($i % 3 == 0) {
        echo "Fizz";
    }
    // 5の倍数の場合
    elseif ($i % 5 == 0) {
        echo "Buzz";
    }
    // 上記以外の場合はその数字を表示
    else {
        echo $i;
    }
    echo "\n";
}
    
echo "1から100までの偶数の合計は " . $sum . " です。";
}